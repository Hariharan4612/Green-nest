export function getCategoriesWithCounts() {
  return categoriesList.map((cat) => {
    if (cat.id === 'all') {
      return { ...cat, count: plants.length };
    }
    if (cat.id === 'air-purifying') {
      const count = plants.filter((p) =>
        p.features?.some((f) => f.toLowerCase().includes('air')) ||
        p.tag?.toLowerCase().includes('air') ||
        p.category.toLowerCase().includes('air')
      ).length;
      return { ...cat, count };
    }
    if (cat.id === 'pet-friendly') {
      const count = plants.filter((p) =>
        p.features?.some((f) => f.toLowerCase().includes('pet')) ||
        p.tag?.toLowerCase().includes('pet') ||
        p.badge?.toLowerCase().includes('pet') ||
        p.toxicity?.toLowerCase().includes('pet friendly') ||
        p.toxicity?.toLowerCase().includes('non-toxic')
      ).length;
      return { ...cat, count };
    }
    const catWords = cat.name.toLowerCase().split(' ');
    const count = plants.filter((p) => {
      const pCat = p.category.toLowerCase();
      return catWords.some(w => w.length > 2 && pCat.includes(w));
    }).length;
    return { ...cat, count };
  });
}

export function filterAndSortPlants({
  category = 'all',
  search = '',
  q = '',
  sortBy = 'popular',
  maxPrice = null,
  featured = false,
  page = 1,
  limit = null
} = {}) {
  const searchTerm = (search || q || '').trim().toLowerCase();
  const catKey = (category || 'all').toLowerCase();

  let results = plants.filter((plant) => {
    if (catKey !== 'all') {
      if (catKey === 'air-purifying') {
        const matchesAir = plant.features?.some((f) => f.toLowerCase().includes('air')) ||
          plant.tag?.toLowerCase().includes('air');
        if (!matchesAir) return false;
      } else if (catKey === 'pet-friendly') {
        const matchesPet = plant.features?.some((f) => f.toLowerCase().includes('pet')) ||
          plant.tag?.toLowerCase().includes('pet') ||
          plant.badge?.toLowerCase().includes('pet') ||
          plant.toxicity?.toLowerCase().includes('pet friendly') ||
          plant.toxicity?.toLowerCase().includes('non-toxic');
        if (!matchesPet) return false;
      } else if (catKey === 'succulents' || catKey === 'succulents & cacti') {
        if (!plant.category.toLowerCase().includes('succulent')) return false;
      } else if (catKey === 'ferns' || catKey === 'ferns & foliage') {
        if (!plant.category.toLowerCase().includes('fern')) return false;
      } else if (catKey === 'indoor' || catKey === 'indoor plants') {
        if (!plant.category.toLowerCase().includes('indoor')) return false;
      } else if (catKey === 'hanging' || catKey === 'hanging plants') {
        if (!plant.category.toLowerCase().includes('hanging')) return false;
      } else if (catKey === 'trees' || catKey === 'indoor trees') {
        if (!plant.category.toLowerCase().includes('tree')) return false;
      } else if (catKey === 'palms' || catKey === 'indoor palms') {
        if (!plant.category.toLowerCase().includes('palm')) return false;
      } else if (catKey === 'herbs') {
        if (!plant.category.toLowerCase().includes('herb')) return false;
      } else if (catKey === 'outdoor' || catKey === 'outdoor plants') {
        if (!plant.category.toLowerCase().includes('outdoor')) return false;
      } else if (catKey === 'flowering' || catKey === 'flowering plants') {
        if (!plant.category.toLowerCase().includes('flowering')) return false;
      } else {
        const matchCat = plant.category.toLowerCase().includes(catKey);
        if (!matchCat) return false;
      }
    }

    if (maxPrice !== null && !isNaN(maxPrice) && plant.price > Number(maxPrice)) {
      return false;
    }

    if (featured && !plant.isPopular) {
      return false;
    }

    if (searchTerm) {
      const matchName = plant.name.toLowerCase().includes(searchTerm);
      const matchSci = plant.scientificName.toLowerCase().includes(searchTerm);
      const matchCat = plant.category.toLowerCase().includes(searchTerm);
      const matchDesc = plant.description.toLowerCase().includes(searchTerm);
      const matchTag = plant.tag.toLowerCase().includes(searchTerm);
      const matchFeat = plant.features.some((f) => f.toLowerCase().includes(searchTerm));
      if (!matchName && !matchSci && !matchCat && !matchDesc && !matchTag && !matchFeat) {
        return false;
      }
    }

    return true;
  });

  results.sort((a, b) => {
    if (sortBy === 'price-low') return a.price - b.price;
    if (sortBy === 'price-high') return b.price - a.price;
    if (sortBy === 'rating') return b.rating - a.rating;
    if (sortBy === 'name') return a.name.localeCompare(b.name);
    if (b.isPopular !== a.isPopular) {
      return (b.isPopular ? 1 : 0) - (a.isPopular ? 1 : 0);
    }
    return b.rating - a.rating;
  });

  const total = results.length;

  if (limit && Number(limit) > 0) {
    const pageNum = Math.max(1, parseInt(page, 10) || 1);
    const limitNum = parseInt(limit, 10);
    const startIndex = (pageNum - 1) * limitNum;
    const paginated = results.slice(startIndex, startIndex + limitNum);
    return {
      plants: paginated,
      total,
      page: pageNum,
      limit: limitNum,
      totalPages: Math.ceil(total / limitNum)
    };
  }

  return {
    plants: results,
    total,
    page: 1,
    limit: total,
    totalPages: 1
  };
}

export function findPlantByIdOrSlug(idOrSlug) {
  if (!idOrSlug) return null;
  const str = String(idOrSlug).trim().toLowerCase();
  return plants.find((p) => String(p.id) === str || p.slug.toLowerCase() === str);
}
